param([string]$JavaHome = 'D:\tool\jdk21', [string]$Python = 'python')
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$env:JAVA_HOME = $JavaHome
function Invoke-Checked([string]$Command, [string[]]$Arguments) {
    & $Command @Arguments
    if ($LASTEXITCODE -ne 0) { throw "检查失败：$Command（返回码 $LASTEXITCODE）" }
}
Push-Location $projectRoot
try {
    $coverageRoot = Join-Path $projectRoot ('artifacts\coverage-' + [guid]::NewGuid().ToString('N'))
    Invoke-Checked 'dotnet' @('test', 'windows/BlueBridge.Core.Tests/BlueBridge.Core.Tests.csproj', '-c', 'Release', '--collect:XPlat Code Coverage', '--results-directory', $coverageRoot)
    $coverageFile = Get-ChildItem -LiteralPath $coverageRoot -Recurse -Filter 'coverage.cobertura.xml' | Select-Object -First 1
    if (!$coverageFile) { throw '未生成 Windows 核心覆盖率报告。' }
    [xml]$coverage = Get-Content -LiteralPath $coverageFile.FullName -Raw
    $lineRate = [double]::Parse($coverage.coverage.'line-rate', [Globalization.CultureInfo]::InvariantCulture)
    if ($lineRate -lt 0.80) { throw "Windows 核心行覆盖率低于80%：$lineRate" }
    Invoke-Checked 'dotnet' @('test', 'windows/BlueBridge.Bluetooth.Tests/BlueBridge.Bluetooth.Tests.csproj', '-c', 'Release', '--collect:XPlat Code Coverage', '--results-directory', (Join-Path $coverageRoot 'bluetooth'))
    Invoke-Checked 'dotnet' @('test', 'windows/BlueBridge.Desktop.Tests/BlueBridge.Desktop.Tests.csproj', '-c', 'Release', '--collect:XPlat Code Coverage', '--results-directory', (Join-Path $coverageRoot 'desktop'), '--', 'DataCollectionRunSettings.DataCollectors.DataCollector.Configuration.Include=[BlueBridge.Desktop.Tests]*', 'DataCollectionRunSettings.DataCollectors.DataCollector.Configuration.IncludeTestAssembly=true', 'DataCollectionRunSettings.DataCollectors.DataCollector.Configuration.Exclude=[BlueBridge.Desktop.Tests]AutoGeneratedProgram', 'DataCollectionRunSettings.DataCollectors.DataCollector.Configuration.ExcludeByFile=**/BlueBridge.Desktop.Tests/*.cs')
    $desktopCoverageFile = Get-ChildItem -LiteralPath (Join-Path $coverageRoot 'desktop') -Recurse -Filter 'coverage.cobertura.xml' | Select-Object -First 1
    if (!$desktopCoverageFile) { throw '未生成 Windows 文件打开逻辑覆盖率报告。' }
    [xml]$desktopCoverage = Get-Content -LiteralPath $desktopCoverageFile.FullName -Raw
    $desktopLineRate = [double]::Parse($desktopCoverage.coverage.'line-rate', [Globalization.CultureInfo]::InvariantCulture)
    if ($desktopLineRate -lt 0.80) { throw "Windows 文件打开逻辑行覆盖率低于80%：$desktopLineRate" }
    foreach ($class in $desktopCoverage.coverage.packages.package.classes.class | Where-Object { $_.name -match 'BlueBridge\.Desktop\.(TransferRecordActions|TransferRow)' }) {
        $rate = [double]::Parse($class.'line-rate', [Globalization.CultureInfo]::InvariantCulture)
        if ($rate -lt 0.80) { throw "Windows 本地文件操作行覆盖率低于80%：$($class.name) $rate" }
    }
    Invoke-Checked 'dotnet' @('build', 'windows/BlueBridge.HeadlessPeer/BlueBridge.HeadlessPeer.csproj', '-c', 'Release')
    Push-Location (Join-Path $projectRoot 'android')
    try { Invoke-Checked '.\gradlew.bat' @(':core:test', ':core:jacocoTestCoverageVerification', ':core:installDist', ':app:testDebugUnitTest', ':app:receivedUiCoverageVerification') }
    finally { Pop-Location }
    $configuration = Join-Path $projectRoot 'artifacts\peer-commands.json'
    $peerCommands = @{
        windows = @((Get-Command dotnet).Source, (Join-Path $projectRoot 'windows\BlueBridge.HeadlessPeer\bin\Release\net10.0\BlueBridge.HeadlessPeer.dll'))
        android = @((Join-Path $JavaHome 'bin\java.exe'), '-cp', (Join-Path $projectRoot 'android\core\build\install\core\lib\*'), 'com.zhanh.bluebridge.core.HeadlessPeerKt')
    }
    $peerCommands | ConvertTo-Json -Depth 4 | Set-Content -LiteralPath $configuration -Encoding utf8
    Invoke-Checked $Python @('tools/cross_language_e2e.py', '--config', $configuration)
    Invoke-Checked $Python @('tools/protocol_abuse_checks.py', '--config', $configuration)
    Invoke-Checked 'dotnet' @('run', '--project', 'tools/DesktopUiCheck/DesktopUiCheck.csproj', '-c', 'Release', '--', 'artifacts/ui')
    Write-Host 'PASS：核心测试、80%行覆盖率门槛、跨语言传输、异常输入与 WPF 界面检查。'
} finally { Pop-Location }
